#!/usr/bin/env python3
"""
AgroSense - price snapshot generator
---------------------------------------------------------------
Pulls WFP market prices for Nigeria from the HDX Humanitarian API
(HAPI) and writes a compact snapshot the dashboard ships with, so the
price board has real figures on first paint and keeps working when the
API is unreachable. The browser refreshes from the same endpoint at
runtime; this file is only the fallback.

    python tools/fetch-prices.py

Writes data/prices-snapshot.js. No third-party packages needed.

Source: https://hapi.humdata.org  (WFP food prices, CC BY-IGO)
"""
import base64
import json
import re
import statistics
import sys
import urllib.parse
import urllib.request
from collections import defaultdict
from datetime import date, datetime, timezone
from pathlib import Path

ENDPOINT = 'https://hapi.humdata.org/api/v2/food-security-nutrition-poverty/food-prices-market-monitor'
APP_ID = base64.b64encode(b'agrosense-dashboard:hello@agrosense.app').decode()
LOCATION = 'NGA'
MONTHS = 24
MIN_MARKETS = 4   # a month needs this many markets reporting to count as complete

# Every WFP commodity the dashboard maps onto a crop or a livestock product.
COMMODITIES = [
    'Maize flour', 'Rice (local)', 'Yam', 'Tomatoes',
    'Meat (beef)', 'Meat (goat)', 'Eggs', 'Fish',
    'Sorghum', 'Millet', 'Cowpeas', 'Groundnuts',
]


def unit_factor(unit):
    """How many of the dashboard's base unit one WFP unit holds."""
    u = unit.strip()
    m = re.match(r'^([\d.]+)\s*KG$', u, re.I)
    if m:
        return 'kg', float(m.group(1))
    if u.upper() == 'KG':
        return 'kg', 1.0
    m = re.match(r'^([\d.]+)\s*G$', u, re.I)
    if m:
        return 'kg', float(m.group(1)) / 1000.0
    m = re.match(r'^([\d.]+)\s*pcs$', u, re.I)
    if m:
        return 'pc', float(m.group(1))
    if u.upper() == 'L':
        return 'L', 1.0
    return 'unit', 1.0


def fetch(commodity, start):
    params = {
        'location_code': LOCATION,
        'commodity_name': commodity,
        'start_date': start,
        'limit': 10000,
        'output_format': 'json',
        'app_identifier': APP_ID,
    }
    url = ENDPOINT + '?' + urllib.parse.urlencode(params)
    with urllib.request.urlopen(url, timeout=120) as res:
        return json.load(res)['data']


def summarise(rows, commodity):
    # commodity_name is a substring filter server-side ("Maize" matches
    # "Maize flour"), so pin it to the exact name here.
    rows = [r for r in rows if r['commodity_name'] == commodity]
    if not rows:
        return None

    unit = rows[0]['unit']
    base, factor = unit_factor(unit)
    by_month = defaultdict(dict)   # month -> market -> price per base unit
    states = set()
    for r in rows:
        month = r['reference_period_start'][:7]
        by_month[month][r['market_name']] = r['price'] / factor
        states.add(r['admin1_name'])

    points = []
    for month in sorted(by_month):
        prices = list(by_month[month].values())
        points.append({
            'm': month,
            'p': round(statistics.median(prices), 2),
            'n': len(prices),
        })

    return {
        'unit': unit,
        'base': base,
        'priceType': rows[0]['price_type'],
        'states': sorted(states),
        'points': points,
    }


def main():
    today = date.today()
    start = f'{today.year - 2}-{today.month:02d}-01'

    series = {}
    for commodity in COMMODITIES:
        sys.stderr.write(f'  {commodity} ... ')
        try:
            rows = fetch(commodity, start)
            summary = summarise(rows, commodity)
        except Exception as err:  # keep going; a missing series is not fatal
            sys.stderr.write(f'failed: {err}\n')
            continue
        if summary:
            series[commodity] = summary
            sys.stderr.write(f'{len(summary["points"])} months, latest {summary["points"][-1]["m"]}\n')
        else:
            sys.stderr.write('no rows\n')

    snapshot = {
        'generatedAt': datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
        'source': 'WFP market monitor via HDX HAPI',
        'endpoint': ENDPOINT,
        'location': LOCATION,
        'minMarkets': MIN_MARKETS,
        'series': series,
    }

    out = Path(__file__).resolve().parent.parent / 'data' / 'prices-snapshot.js'
    out.parent.mkdir(exist_ok=True)
    body = json.dumps(snapshot, separators=(',', ':'))
    out.write_text(
        '/* Generated by tools/fetch-prices.py - do not edit by hand.\n'
        '   Bundled fallback for the WFP price feed; the browser refreshes\n'
        '   from HDX HAPI at runtime. */\n'
        'window.AgroSense = window.AgroSense || {};\n'
        f'window.AgroSense.pricesSnapshot = {body};\n',
        encoding='utf-8',
    )
    sys.stderr.write(f'wrote {out} ({out.stat().st_size // 1024} KB)\n')


if __name__ == '__main__':
    main()
